test('exports are read back', async ({ page }) => {
  await analyse(page, HAND)
  await openTab(page, 'Setup')
  await page.getByLabel('Method').selectOption('livak')
  await openTab(page, 'Reference genes')
  await page.getByLabel('Normalise to R').check()
  await openTab(page, 'Results')
  // Relative expression against the control mean dCq 11: 2^1, 2^0, 2^-1, 2^3, 2^2, 2^1.
  const [name, csv] = await download(page, page.getByRole('button', { name: 'Per-sample CSV' }))
  expect(name).toBe('e2e-run-samples.csv')
  expect(csvRows(csv).slice(1).map(r => r.slice(-3))).toEqual([['10', '1', '2'], ['11', '0', '1'], ['12', '-1', '0.5'], ['8', '3', '8'], ['9', '2', '4'], ['10', '1', '2']])
  const [, book] = await download(page, page.getByRole('button', { name: 'XLSX workbook' }))
  const wb = XLSX.read(book)
  expect(wb.SheetNames.slice(0, 4)).toEqual(['Comparisons', 'Samples', 'Replicates', 'QC'])
  expect((XLSX.utils.sheet_to_json(wb.Sheets.Comparisons) as Record<string, unknown>[])[0]['Fold change']).toBe(4)
  const [, svg] = await download(page, page.getByRole('button', { name: 'SVG' }))
  expect(svg.toString()).toContain('T Trt 4x ns')
  const [, png] = await download(page, page.getByRole('button', { name: 'PNG' }))
  expect(png.subarray(0, 4)).toEqual(Buffer.from([0x89, 0x50, 0x4e, 0x47]))
})

test('markup in names is shown as text on screen, in the figure and in the report', async ({ page }) => {
  const evil = '<img src=x onerror=alert(1)>'
  const dialogs: string[] = []
  page.on('dialog', d => { dialogs.push(d.message()); void d.dismiss() })
  await analyse(page, HAND.replace(/Trt/g, evil).replace(/,T,/g, `,${evil},`))
  await openTab(page, 'Reference genes')
  await page.getByLabel('Normalise to R').check()
  await openTab(page, 'Results')
  await expect(page.locator('.main-fig')).toContainText(evil)
  const [, svg] = await download(page, page.getByRole('button', { name: 'SVG' }))
  expect(svg.toString()).not.toContain('<img')
  await page.getByRole('link', { name: 'Printable QC report' }).click()
  await expect(page.locator('.report .fig')).toContainText(evil)
  await expect(page.locator('img')).toHaveCount(0)
  expect(dialogs).toEqual([])
})


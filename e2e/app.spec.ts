test('settings, plates and exclusions survive a reload; undo works', async ({ page }) => {
  await analyse(page, HAND)
  await openTab(page, 'Setup')
  await page.getByLabel('Method').selectOption('livak')
  await fillAndLeave(page.getByLabel('RNA quality'), 'RIN 9.1')
  await openTab(page, 'QC')
  await page.getByLabel(/Flagged only/).uncheck()
  await page.getByRole('button', { name: /^B1 / }).click()
  await page.reload()
  await page.getByLabel(/Flagged only/).uncheck()
  await expect(page.getByRole('button', { name: /^B1 .*excluded/ })).toBeVisible()
  await openTab(page, 'Setup')
  await expect(page.getByLabel('Method')).toHaveValue('livak')
  await expect(page.getByLabel('RNA quality')).toHaveValue('RIN 9.1')
  await page.goto('/app')
  await page.getByRole('row', { name: /E2E run/ }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByRole('link', { name: 'E2E run' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(page.getByRole('link', { name: 'E2E run' })).toBeVisible()
})

